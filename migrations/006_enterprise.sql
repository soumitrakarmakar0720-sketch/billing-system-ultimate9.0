BEGIN;
CREATE TABLE IF NOT EXISTS branch (id SERIAL PRIMARY KEY, name VARCHAR(120) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS staff_branch (user_id INTEGER PRIMARY KEY REFERENCES "user"(id), branch_id INTEGER NOT NULL REFERENCES branch(id));
CREATE TABLE IF NOT EXISTS terminal_presence (user_id INTEGER PRIMARY KEY REFERENCES "user"(id), seen_at TIMESTAMPTZ NOT NULL);
CREATE TABLE IF NOT EXISTS bill_branch (order_id INTEGER PRIMARY KEY REFERENCES "order"(id), branch_id INTEGER NOT NULL REFERENCES branch(id));
COMMIT;
